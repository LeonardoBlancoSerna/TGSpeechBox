#[test]
fn voicing_tone_defaults_match_cpp_bits() {
    let t = VoicingTone::defaults();
    let want_u32: HashMap<&str, u32> = [
        ("magic", t.magic),
        ("structSize", t.struct_size),
        ("structVersion", t.struct_version),
        ("dspVersion", t.dsp_version),
    ]
    .into_iter()
    .collect();
    let want_bits: HashMap<&str, u64> = [
        ("voicingPeakPos", t.voicing_peak_pos.to_bits()),
        ("voicedPreEmphA", t.voiced_pre_emph_a.to_bits()),
        ("voicedPreEmphMix", t.voiced_pre_emph_mix.to_bits()),
        ("highShelfGainDb", t.high_shelf_gain_db.to_bits()),
        ("highShelfFcHz", t.high_shelf_fc_hz.to_bits()),
        ("highShelfQ", t.high_shelf_q.to_bits()),
        ("voicedTiltDbPerOct", t.voiced_tilt_db_per_oct.to_bits()),
        (
            "noiseGlottalModDepth",
            t.noise_glottal_mod_depth.to_bits(),
        ),
        ("pitchSyncF1DeltaHz", t.pitch_sync_f1_delta_hz.to_bits()),
        ("pitchSyncB1DeltaHz", t.pitch_sync_b1_delta_hz.to_bits()),
        ("speedQuotient", t.speed_quotient.to_bits()),
        (
            "aspirationTiltDbPerOct",
            t.aspiration_tilt_db_per_oct.to_bits(),
        ),
        ("cascadeBwScale", t.cascade_bw_scale.to_bits()),
        ("tremorDepth", t.tremor_depth.to_bits()),
        ("nasalBwScale", t.nasal_bw_scale.to_bits()),
        ("f4FreqScale", t.f4_freq_scale.to_bits()),
        ("nasalGainScale", t.nasal_gain_scale.to_bits()),
        ("chorusDepth", t.chorus_depth.to_bits()),
        ("chorusDetuneHz", t.chorus_detune_hz.to_bits()),
    ]
    .into_iter()
    .collect();

    let (mut n_u32, mut n_bits) = (0, 0);
    for r in load() {
        match r {
            Rec::U32(st, field, v) => {
                if st == "speechPlayer_voicingTone_t" {
                    let w = want_u32
                        .get(field.as_str())
                        .unwrap_or_else(|| panic!("unknown VoicingTone u32 {field}"));
                    assert_eq!(*w, v, "VoicingTone u32 mismatch for {field}");
                    n_u32 += 1;
                }
            }
            Rec::Bits(st, field, bits) => {
                if st == "speechPlayer_voicingTone_t" {
                    let w = want_bits
                        .get(field.as_str())
                        .unwrap_or_else(|| panic!("unknown VoicingTone default {field}"));
                    assert_eq!(*w, bits, "VoicingTone default mismatch for {field}");
                    n_bits += 1;
                }
            }
            _ => {}
        }
    }
    assert_eq!(n_u32, want_u32.len());
    assert_eq!(n_bits, want_bits.len());
}
