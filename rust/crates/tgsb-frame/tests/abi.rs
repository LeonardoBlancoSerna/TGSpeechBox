fn rust_sizeof(st: &str) -> usize {
    match st {
        "speechPlayer_frame_t" => size_of::<Frame>(),
        "speechPlayer_frameEx_t" => size_of::<FrameEx>(),
        "speechPlayer_voicingTone_t" => size_of::<VoicingTone>(),
        "sample" => size_of::<Sample>(),
        other => panic!("unknown struct in reference: {other}"),
    }
}

#[test]
fn sizes_and_scalars_match_cpp() {
    let recs = load();
    let mut sizes = 0;
    for r in &recs {
        if let Rec::Size(st, n) = r {
            assert_eq!(rust_sizeof(st), *n, "sizeof mismatch for {st}");
            sizes += 1;
        }
    }
    assert_eq!(sizes, 4, "expected 4 sizeof lines in reference");

    let scalars: HashMap<&str, usize> = recs
        .iter()
        .filter_map(|r| match r {
            Rec::Scalar(k, v) => Some((k.as_str(), *v)),
            _ => None,
        })
        .collect();
    assert_eq!(
        scalars["speechPlayer_frame_numParams"],
        FRAME_NUM_PARAMS
    );
    assert_eq!(
        scalars["speechPlayer_frameEx_numParams"],
        FRAMEEX_NUM_PARAMS
    );
    assert_eq!(scalars["SPEECHPLAYER_DSP_VERSION"], DSP_VERSION as usize);
    assert_eq!(
        scalars["SPEECHPLAYER_VOICINGTONE_MAGIC"],
        VOICINGTONE_MAGIC as usize
    );
    assert_eq!(
        scalars["SPEECHPLAYER_VOICINGTONE_VERSION"],
        VOICINGTONE_VERSION as usize
    );
}

#[test]
fn offsets_match_cpp() {
    let recs = load();
    let expected = expected_offsets();

    let mut seen: HashMap<(&str, &str), usize> = HashMap::new();
    for r in &recs {
        if let Rec::Offset(st, field, off) = r {
            let key = (st.as_str(), field.as_str());
            let want = expected
                .get(&key)
                .unwrap_or_else(|| panic!("reference has unknown field {st}.{field}"));
            assert_eq!(*want, *off, "offset mismatch for {st}.{field}");
            assert!(
                seen.insert(key, *off).is_none(),
                "duplicate offset line for {st}.{field}"
            );
        }
    }

    // Every Rust field must be present in the reference (catches fields the
    // C++ dump was not regenerated for, and vice versa).
    for (key, _) in &expected {
        assert!(
            seen.contains_key(key),
            "missing offset line for {}.{}",
            key.0,
            key.1
        );
    }
    assert_eq!(seen.len(), expected.len());
}

