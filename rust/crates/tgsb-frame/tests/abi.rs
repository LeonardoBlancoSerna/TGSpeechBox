use std::collections::HashMap;
use std::mem::{offset_of, size_of};
use tgsb_frame::{
    Frame, FrameEx, Sample, VoicingTone, DSP_VERSION, FRAMEEX_NUM_PARAMS, FRAME_NUM_PARAMS,
    VOICINGTONE_MAGIC, VOICINGTONE_VERSION,
};

const REF: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../harness/abi_reference.txt"
);

enum Rec {
    Size(String, usize),
    Scalar(String, usize),
    Offset(String, String, usize),
    Bits(String, String, u64),
    U32(String, String, u32),
}

fn load() -> Vec<Rec> {
    let text = std::fs::read_to_string(REF)
        .unwrap_or_else(|e| panic!("cannot read {REF}: {e} (run build_abi_dump.ps1)"));
    let mut out = Vec::new();
    for line in text.lines() {
        let t: Vec<&str> = line.split_whitespace().collect();
        match t.as_slice() {
            ["sizeof", s, n] => out.push(Rec::Size(
                s.to_string(),
                n.parse().expect("sizeof value"),
            )),
            ["scalar", s, n] => out.push(Rec::Scalar(
                s.to_string(),
                n.parse().expect("scalar value"),
            )),
            ["offset", s, f, n] => out.push(Rec::Offset(
                s.to_string(),
                f.to_string(),
                n.parse().expect("offset value"),
            )),
            ["bits", s, f, h] => out.push(Rec::Bits(
                s.to_string(),
                f.to_string(),
                u64::from_str_radix(h.trim_start_matches("0x"), 16).expect("bits hex"),
            )),
            ["u32", s, f, h] => out.push(Rec::U32(
                s.to_string(),
                f.to_string(),
                u32::from_str_radix(h.trim_start_matches("0x"), 16).expect("u32 hex"),
            )),
            [] => {}
            other => panic!("unrecognized reference line: {other:?}"),
        }
    }
    out
}

/// Builds (struct, c-field) -> offset from pairs written against the real
/// Rust type, so a renamed/reordered Rust field fails here.
macro_rules! offsets {
    ($st:literal, $ty:ty; $($c:literal => $f:ident),+ $(,)?) => {{
        let mut m: HashMap<(&'static str, &'static str), usize> = HashMap::new();
        $( m.insert(($st, $c), offset_of!($ty, $f)); )+
        m
    }};
}

